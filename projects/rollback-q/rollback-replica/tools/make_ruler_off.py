"""turn sheets/ruler_res.txt (tick residuals of the source ruler vs the ideal grid) into scripts/ruler_off.py:
RULER_OFF[f] = world-px offset of the ruler at frame f (hold-keyed on the ruler tiles)."""
import re, io, os
import numpy as np

PM = 5 * 7.2654
rows = {}
for ln in io.open('sheets/ruler_res.txt', encoding='utf-8'):
    m = re.match(r'\s*(\d+) s=([\d.]+) cx=\s*([\d.]+)\s+ticks=\s*(\d+) kept=\s*(\d+)\s+res=\s*([-+\d.]+)\s+slope=([-+\d.]+)/1000px\s+rms=([\d.]+)', ln)
    if m:
        f = int(m.group(1))
        rows[f] = dict(s=float(m.group(2)), kept=int(m.group(5)), res=float(m.group(6)), rms=float(m.group(8)))

# shots = runs of frames where one value (median of the reliable frames) is used; None = per-frame values
SHOTS = [
    (0, 2, 'frame'), (3, 13, 'median'), (14, 25, 'frame'), (26, 36, 'frame'), (37, 56, 'frame'), (57, 71, 'frame'),
    (72, 72, 'frame'), (73, 73, 'frame'), (74, 78, 'frame'), (79, 83, 'frame'), (84, 85, 'median'), (86, 86, 'frame'),
    (87, 88, 'median'), (89, 90, 'median'), (91, 93, 'median'), (94, 97, 'median'), (98, 102, 'median'), (103, 103, 'frame'),
    (104, 136, 'median'), (137, 143, 'frame'), (144, 150, 'frame'), (151, 164, 'frame'), (165, 176, 'frame'), (177, 177, 'frame'),
    (178, 198, 'median'), (199, 201, 'frame'), (202, 205, 'median'), (206, 226, 'hold'), (227, 256, 'fit'), (257, 271, 'hold'),
]


def good(f):
    r = rows.get(f)
    return r is not None and r['kept'] >= 12 and r['rms'] < 1.0


def good_loose(f):
    r = rows.get(f)
    return r is not None and r['kept'] >= 12 and r['rms'] < 2.3


off = [None] * 272
prev = -12.5
for a, b, mode in SHOTS:
    fr = list(range(a, b + 1))
    g = [f for f in fr if good(f)]
    if mode == 'fit' or len(g) < max(1, len(fr) // 3):
        g = [f for f in fr if good_loose(f)]
    if mode == 'hold' or not g:
        for f in fr:
            off[f] = prev
        continue
    vals = np.array([rows[f]['res'] for f in g])
    # unwrap around the circular mean
    m = np.angle(np.exp(1j * vals / PM * 2 * np.pi).mean()) / (2 * np.pi) * PM
    vals = (vals - m + PM / 2) % PM - PM / 2 + m
    med = float(np.median(vals))
    if mode == 'median':
        for f in fr:
            off[f] = med
    elif mode == 'fit':
        p = np.polyfit(np.array(g, float), vals, 1)
        for f in fr:
            off[f] = float(np.polyval(p, f))
    else:
        d = dict(zip(g, vals))
        for f in fr:
            if f in d and abs(d[f] - med) < 4.0:
                off[f] = float(d[f])
            else:
                near = min(g, key=lambda q: abs(q - f))
                off[f] = float(d[near]) if abs(d[near] - med) < 4.0 else med
    prev = off[b]

out = os.path.join(r'C:\Users\bg931\Documents\New project\rollback-replica\scripts', 'ruler_off.py')
with io.open(out, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('"""Measured offset (world px) of the source ruler against the ideal tick grid, per frame.\n'
             'Generated by tools/make_ruler_off.py from the tick-residual audit; the ruler tiles get these as hold keys."""\n')
    fh.write('RULER_OFF = [\n')
    for i in range(0, 272, 8):
        fh.write('    ' + ', '.join('%.2f' % v for v in off[i:i + 8]) + ',\n')
    fh.write(']\n')
print('written', out)
for a, b, mode in SHOTS:
    print(a, b, mode, ['%.1f' % off[f] for f in range(a, min(b, a + 7) + 1)])
