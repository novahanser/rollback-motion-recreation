def build_cx():
    cx = [None] * N
    # intro .. f71 by integrating the flow, anchored so that f26 == 667.1 (panorama registration)
    acc = [0.0] * 72
    for f in range(1, 72):
        acc[f] = acc[f - 1] + FLOW[f] * (P0 / 7.3333)
    off = 667.1 - acc[26]
    for f in range(72):
        cx[f] = acc[f] + off + CX_FIX.get(f, 0.0)
    for f, v in CX_ABS.items():
        cx[f] = v
    for f in range(178, 199):          # steady drift
        cx[f] = 6594.6 + 13.36 * (f - 178)
    for f in range(227, 257):          # slow drift under the title
        cx[f] = 9803.5 + 3.8 * (f - 227)
    missing = [f for f in range(N) if cx[f] is None]
    assert not missing, missing
    return cx


def build():
    s = build_s()
    cx = build_cx()
    return [dict(f=f, s=round(s[f], 5), cx=round(cx[f], 2)) for f in range(N)]


